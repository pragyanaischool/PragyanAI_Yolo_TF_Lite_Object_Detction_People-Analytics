
import React from "react";

import {
  Download,
  FileSpreadsheet,
  FileVideo,
  FileJson
} from "lucide-react";

function DownloadReport({
  videoUrl,
  csvUrl,
  results
}) {
  const downloadFile = async (url, filename) => {
    if (!url) {
      alert("Download file is not available.");
      return;
    }

    try {
      const response = await fetch(url);

      if (!response.ok) {
        throw new Error("Download failed.");
      }

      const blob = await response.blob();

      const objectUrl = URL.createObjectURL(blob);

      const link = document.createElement("a");

      link.href = objectUrl;
      link.download = filename;

      document.body.appendChild(link);
      link.click();
      link.remove();

      URL.revokeObjectURL(objectUrl);

    } catch (error) {
      console.error("Download error:", error);

      // Fallback to opening the file URL
      window.open(url, "_blank", "noopener,noreferrer");
    }
  };

  const downloadJSON = () => {
    if (!results) return;

    const blob = new Blob(
      [JSON.stringify(results, null, 2)],
      { type: "application/json" }
    );

    const objectUrl = URL.createObjectURL(blob);

    const link = document.createElement("a");

    link.href = objectUrl;
    link.download = "pragyanai_people_analytics.json";

    document.body.appendChild(link);
    link.click();
    link.remove();

    URL.revokeObjectURL(objectUrl);
  };

  return (
    <section className="download-card">

      <h3>Download Reports</h3>

      <p>
        Download your processed video and analytics
        generated by the AI detection system.
      </p>

      <div className="download-actions">

        {/* Processed Video */}
        <button
          type="button"
          className="download-button"
          disabled={!videoUrl}
          onClick={() =>
            downloadFile(
              videoUrl,
              "pragyanai_processed_video.mp4"
            )
          }
        >
          <FileVideo size={17} />
          <Download size={15} />
          Download Video
        </button>

        {/* CSV Report */}
        <button
          type="button"
          className="download-button secondary"
          disabled={!csvUrl}
          onClick={() =>
            downloadFile(
              csvUrl,
              "pragyanai_people_analytics.csv"
            )
          }
        >
          <FileSpreadsheet size={17} />
          <Download size={15} />
          Download CSV
        </button>

        {/* JSON Report */}
        <button
          type="button"
          className="download-button secondary"
          disabled={!results}
          onClick={downloadJSON}
        >
          <FileJson size={17} />
          <Download size={15} />
          Download JSON
        </button>

      </div>

    </section>
  );
}

export default DownloadReport;
